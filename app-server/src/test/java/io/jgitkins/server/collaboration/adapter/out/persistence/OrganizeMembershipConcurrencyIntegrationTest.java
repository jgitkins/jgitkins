package io.jgitkins.server.collaboration.adapter.out.persistence;

import static org.assertj.core.api.Assertions.assertThat;

import io.jgitkins.server.collaboration.application.exception.OrganizeAccessDeniedException;
import io.jgitkins.server.collaboration.application.service.OrganizeMemberService;
import io.jgitkins.server.collaboration.domain.entity.OrganizeMember;
import io.jgitkins.server.collaboration.domain.repository.OrganizeRepository;
import io.jgitkins.server.collaboration.domain.vo.OrganizeMemberRole;
import io.jgitkins.server.collaboration.domain.vo.MemberUserId;
import io.jgitkins.server.collaboration.adapter.out.persistence.support.OrganizeDomainMapper;
import io.jgitkins.server.collaboration.adapter.out.persistence.support.OrganizeMemberDomainMapper;
import io.jgitkins.server.collaboration.adapter.out.persistence.mapper.OrganizeEntityMbgMapper;
import io.jgitkins.server.collaboration.adapter.out.persistence.mapper.OrganizeMemberEntityMbgMapper;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CyclicBarrier;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;
import javax.sql.DataSource;
import org.apache.ibatis.session.SqlSessionFactory;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;
import org.mybatis.spring.SqlSessionFactoryBean;
import org.mybatis.spring.SqlSessionTemplate;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.transaction.support.TransactionTemplate;

class OrganizeMembershipConcurrencyIntegrationTest {

    private EmbeddedDatabase dataSource;
    private JdbcTemplate jdbcTemplate;
    private OrganizeRepository organizeRepository;
    private OrganizeMemberPersistenceAdapter memberRepository;
    private OrganizeMemberService service;
    private TransactionTemplate transactionTemplate;
    private Long organizeId;
    private CountDownLatch firstLockAcquired;
    private CountDownLatch secondLockAttempted;
    private CountDownLatch releaseFirstLock;

    @BeforeEach
    void setUp() throws Exception {
        dataSource = new EmbeddedDatabaseBuilder().generateUniqueName(true).setType(EmbeddedDatabaseType.H2).build();
        jdbcTemplate = new JdbcTemplate(dataSource);
        jdbcTemplate.execute("create table ORGANIZE (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(255) NOT NULL, PATH VARCHAR(255) NOT NULL, OWNER_ID BIGINT NOT NULL, CREATED_AT TIMESTAMP NOT NULL, UPDATED_AT TIMESTAMP NOT NULL, DESCRIPTION CLOB)");
        jdbcTemplate.execute("create table ORGANIZE_MEMBER (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ORGANIZE_ID BIGINT NOT NULL, USER_ID BIGINT NOT NULL, ROLE VARCHAR(32) NOT NULL, JOINED_AT TIMESTAMP NOT NULL, UNIQUE (ORGANIZE_ID, USER_ID))");
        SqlSessionFactory factory = sqlSessionFactory(dataSource);
        OrganizePersistenceAdapter realOrganizeRepository = new OrganizePersistenceAdapter(
                new SqlSessionTemplate(factory).getMapper(OrganizeEntityMbgMapper.class),
                org.mapstruct.factory.Mappers.getMapper(OrganizeDomainMapper.class));
        memberRepository = new OrganizeMemberPersistenceAdapter(
                new SqlSessionTemplate(factory).getMapper(OrganizeMemberEntityMbgMapper.class),
                org.mapstruct.factory.Mappers.getMapper(OrganizeMemberDomainMapper.class));
        firstLockAcquired = new CountDownLatch(1);
        secondLockAttempted = new CountDownLatch(1);
        releaseFirstLock = new CountDownLatch(1);
        AtomicInteger lockCalls = new AtomicInteger();
        OrganizeRepository lockedRepository = Mockito.spy(realOrganizeRepository);
        Mockito.doAnswer(invocation -> {
            int call = lockCalls.incrementAndGet();
            if (call > 1) {
                secondLockAttempted.countDown();
            }
            var result = realOrganizeRepository.lockByIdForMembershipMutation(invocation.getArgument(0));
            if (call == 1) {
                firstLockAcquired.countDown();
                if (!releaseFirstLock.await(10, TimeUnit.SECONDS)) {
                    throw new IllegalStateException("first lock release timed out");
                }
            }
            return result;
        }).when(lockedRepository).lockByIdForMembershipMutation(Mockito.any());
        organizeRepository = lockedRepository;
        service = new OrganizeMemberService(memberRepository, memberRepository, organizeRepository);
        transactionTemplate = new TransactionTemplate(new DataSourceTransactionManager(dataSource));
        transactionTemplate.executeWithoutResult(status -> {
            var saved = organizeRepository.save(io.jgitkins.server.collaboration.domain.aggregate.Organize.createWithoutEvent(
                    null, io.jgitkins.server.collaboration.domain.vo.OrganizeName.from("race"),
                    io.jgitkins.server.collaboration.domain.vo.OrganizeOwnerId.of(7L), "description", java.time.LocalDateTime.now()));
            organizeId = saved.getId().getValue();
            memberRepository.save(OrganizeMember.create(saved.getId(), MemberUserId.of(7L), OrganizeMemberRole.OWNER, null));
            memberRepository.save(OrganizeMember.create(saved.getId(), MemberUserId.of(8L), OrganizeMemberRole.OWNER, null));
        });
    }

    @AfterEach
    void tearDown() {
        dataSource.shutdown();
    }

    @Test
    void concurrentDistinctOwnerSelfRemovalLeavesExactlyOneOwner() throws Exception {
        CyclicBarrier start = new CyclicBarrier(2);
        ExecutorService executor = Executors.newFixedThreadPool(2);
        try {
            List<Future<String>> results = new ArrayList<>();
            results.add(executor.submit(() -> attemptSelfRemove(start, 7L)));
            results.add(executor.submit(() -> attemptSelfRemove(start, 8L)));

            assertThat(firstLockAcquired.await(10, TimeUnit.SECONDS)).isTrue();
            assertThat(secondLockAttempted.await(10, TimeUnit.SECONDS)).isTrue();
            releaseFirstLock.countDown();

            List<String> outcomes = results.stream().map(future -> {
                try {
                    return future.get(30, TimeUnit.SECONDS);
                } catch (Exception e) {
                    throw new RuntimeException(e);
                }
            }).toList();

            assertThat(outcomes).containsExactlyInAnyOrder("success", "denied");
            assertThat(jdbcTemplate.queryForObject("select count(*) from ORGANIZE_MEMBER where ROLE = 'OWNER'", Integer.class))
                    .isEqualTo(1);
            assertThat(jdbcTemplate.queryForObject(
                    "select USER_ID from ORGANIZE_MEMBER where ORGANIZE_ID = ? and ROLE = 'OWNER'",
                    Long.class, organizeId)).isIn(7L, 8L);
        } finally {
            releaseFirstLock.countDown();
            executor.shutdownNow();
            assertThat(executor.awaitTermination(10, TimeUnit.SECONDS)).isTrue();
        }
    }

    private String attemptSelfRemove(CyclicBarrier start, long userId) {
        try {
            start.await(10, TimeUnit.SECONDS);
            transactionTemplate.executeWithoutResult(status -> service.removeOrganizeMember(organizeId, userId, userId));
            return "success";
        } catch (OrganizeAccessDeniedException e) {
            return "denied";
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
    }

    private SqlSessionFactory sqlSessionFactory(DataSource dataSource) throws Exception {
        SqlSessionFactoryBean factoryBean = new SqlSessionFactoryBean();
        factoryBean.setDataSource(dataSource);
        factoryBean.setMapperLocations(
                new ClassPathResource("mapper/mbg/OrganizeEntityMbgMapper.xml"),
                new ClassPathResource("mapper/mbg/OrganizeMemberEntityMbgMapper.xml"));
        factoryBean.setConfiguration(new org.apache.ibatis.session.Configuration());
        factoryBean.afterPropertiesSet();
        return factoryBean.getObject();
    }
}
