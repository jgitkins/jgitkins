package io.jgitkins.server.collaboration.adapter.out.persistence;

import static org.assertj.core.api.Assertions.assertThat;

import io.jgitkins.server.collaboration.domain.aggregate.Organize;
import io.jgitkins.server.collaboration.domain.event.OrganizeCreatedEvent;
import io.jgitkins.server.collaboration.domain.vo.OrganizeName;
import io.jgitkins.server.collaboration.domain.vo.OwnerId;
import io.jgitkins.server.collaboration.adapter.out.persistence.support.OrganizeDomainMapper;
import io.jgitkins.server.collaboration.adapter.out.persistence.mapper.OrganizeEntityMbgMapper;
import java.time.Instant;
import java.time.LocalDateTime;
import javax.sql.DataSource;
import org.apache.ibatis.session.SqlSessionFactory;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mybatis.spring.SqlSessionFactoryBean;
import org.mybatis.spring.SqlSessionTemplate;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;

class OrganizePersistenceAdapterIntegrationTest {

    private EmbeddedDatabase dataSource;
    private JdbcTemplate jdbcTemplate;
    private OrganizePersistenceAdapter adapter;

    @BeforeEach
    void setUp() throws Exception {
        dataSource = new EmbeddedDatabaseBuilder()
                .generateUniqueName(true)
                .setType(EmbeddedDatabaseType.H2)
                .build();
        jdbcTemplate = new JdbcTemplate(dataSource);
        jdbcTemplate.execute("""
                create table ORGANIZE (
                    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    NAME VARCHAR(255) NOT NULL,
                    PATH VARCHAR(255) NOT NULL,
                    OWNER_ID BIGINT NOT NULL,
                    CREATED_AT TIMESTAMP NOT NULL,
                    UPDATED_AT TIMESTAMP NOT NULL,
                    DESCRIPTION CLOB
                )
                """);

        SqlSessionFactory sqlSessionFactory = sqlSessionFactory(dataSource);
        OrganizeEntityMbgMapper mapper = new SqlSessionTemplate(sqlSessionFactory)
                .getMapper(OrganizeEntityMbgMapper.class);
        adapter = new OrganizePersistenceAdapter(mapper,
                org.mapstruct.factory.Mappers.getMapper(OrganizeDomainMapper.class));
    }

    @AfterEach
    void tearDown() {
        dataSource.shutdown();
    }

    @Test
    void save_returnsGeneratedIdThatMatchesDatabaseRowAndCreatedEvent() {
        Organize organize = Organize.createWithoutEvent(
                null,
                OrganizeName.from("integration-org"),
                OwnerId.of(7L),
                "description",
                LocalDateTime.of(2026, 8, 18, 9, 0));

        Organize saved = adapter.save(organize);
        saved.recordCreated(Instant.parse("2026-08-18T00:00:00Z"));

        Long rowId = jdbcTemplate.queryForObject(
                "select ID from ORGANIZE where NAME = ?", Long.class, "integration-org");
        OrganizeCreatedEvent event = (OrganizeCreatedEvent) saved.getDomainEvents().get(0);

        assertThat(saved.getId()).isNotNull();
        assertThat(rowId).isEqualTo(saved.getId().getValue());
        assertThat(event.getOrganizeId()).isEqualTo(saved.getId());
    }

    private SqlSessionFactory sqlSessionFactory(DataSource dataSource) throws Exception {
        SqlSessionFactoryBean factoryBean = new SqlSessionFactoryBean();
        factoryBean.setDataSource(dataSource);
        factoryBean.setMapperLocations(new ClassPathResource(
                "mapper/mbg/OrganizeEntityMbgMapper.xml"));
        factoryBean.setConfiguration(new org.apache.ibatis.session.Configuration());
        factoryBean.afterPropertiesSet();
        return factoryBean.getObject();
    }
}
